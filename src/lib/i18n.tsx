const DICTS: Record<LangCode, Dict> = { en, hi, gu, mr, ta, pa, bn };

type Ctx = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: TKey) => string;
};

const I18nContext = createContext<Ctx | null>(null);

function isLang(v: string | null): v is LangCode {
  return !!v && LANGUAGES.some((l) => l.code === v);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const saved = typeof window !== "undefined" ? window.localStorage.getItem(STORAGE_KEY) : null;
    if (isLang(saved)) setLangState(saved);
  }, []);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
      document.documentElement.lang = l;
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback((key: TKey) => DICTS[lang][key] ?? en[key], [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) return { lang: "en", setLang: () => {}, t: (k: TKey) => en[k] };
  return ctx;
}
